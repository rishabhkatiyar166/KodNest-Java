public class classPracticeElse {
    public static void main(String[] args) {
        int number = 25;

        if (number > 0) {
            System.out.println("Number type: Positive");
        } else if (number < 0) {
            System.out.println("Number type: Negative");
        } else {
            System.out.println("Number type: Zero");
        }
    }
}
